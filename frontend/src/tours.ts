// Short guided tours, one per page of the admin panel. A page's tour runs by itself the first time the administrator
// opens that page, and again from «?» in the sidebar. Each step spotlights one part of the page (CSS selectors tried
// in order; none found = the box sits in the middle) and says what it does and what it keeps.

export interface TourStep {
  /** Page the step is on — only the full walkthrough moves between pages. */
  route?: string
  target?: string[]
  /** A sidebar element: on a phone the menu drawer opens for it. */
  menu?: boolean
  /** Skipped when its element isn't on the page (e.g. «Первые шаги» once orders come in). */
  optional?: boolean
  title: string
  text: string
}

