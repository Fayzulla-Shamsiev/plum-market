// Storefront languages match the catalog content languages: Russian, Uzbek (Latin), Uzbek (Cyrillic).
export type Lang = 'ru' | 'uz' | 'oz'
export const langs: { code: Lang; label: string; short: string }[] = [
  { code: 'ru', label: 'Русский', short: 'Рус' },
  { code: 'uz', label: "O'zbekcha", short: "O'zb" },
  { code: 'oz', label: 'Ўзбекча', short: 'Ўзб' },
]

function readLang(): Lang {
  try {
    const v = localStorage.getItem('plum.shop.lang')
    return v === 'uz' || v === 'oz' ? v : 'ru'
  } catch {
    return 'ru'
  }
}

export const lang = ref<Lang>(readLang())
export function setLang(v: Lang) {
  lang.value = v
  document.documentElement.lang = v === 'ru' ? 'ru' : 'uz'
  try { localStorage.setItem('plum.shop.lang', v) } catch { /* private mode */ }
}

