export type Key = keyof typeof dict
const idx = computed(() => ({ ru: 0, uz: 1, oz: 2 })[lang.value])
export const t = (k: Key) => dict[k][idx.value]

const nf = new Intl.NumberFormat('ru-RU')
export const price = (v: number) => `${nf.format(v)} ${t('sum')}`

export function weight(grams: number | null) {
  if (!grams) return ''
  return grams >= 1000 ? `${(grams / 1000).toLocaleString('ru-RU')} ${t('kg')}` : `${grams} ${t('g')}`
}

const dateFmt = computed(() => new Intl.DateTimeFormat(lang.value === 'ru' ? 'ru-RU' : 'uz-UZ', { day: 'numeric', month: 'long', year: 'numeric' }))
export const longDate = (iso: string) => dateFmt.value.format(new Date(iso))

// Russian needs three plural forms (1 товар, 2 товара, 5 товаров); Uzbek uses one ("5 ta mahsulot").
const ruForms = {
  items: ['товар', 'товара', 'товаров'],
  reviews: ['отзыв', 'отзыва', 'отзывов'],
  branches: ['филиал', 'филиала', 'филиалов'],
  pcs: ['шт', 'шт', 'шт'],
} as const
export function count(n: number, key: keyof typeof ruForms): string {
  if (lang.value !== 'ru') return `${n} ${t(key)}`
  const m10 = n % 10, m100 = n % 100
  const form = m10 === 1 && m100 !== 11 ? 0 : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 1 : 2
  return `${n} ${ruForms[key][form]}`
}

const dtFmt = computed(() => new Intl.DateTimeFormat(lang.value === 'ru' ? 'ru-RU' : 'uz-UZ', { day: 'numeric', month: 'long', hour: '2-digit', minute: '2-digit' }))
export const dateTime = (iso: string) => dtFmt.value.format(new Date(iso))

/** "+998 90 123 45 67" from any 9 digits (for display while typing). */
export function formatPhone(digits: string) {
  const d = digits.replace(/\D/g, '').slice(0, 9)
  return [d.slice(0, 2), d.slice(2, 5), d.slice(5, 7), d.slice(7, 9)].filter(Boolean).join(' ')
}
